_WINDOWS_LOWER = {name.lower(): iana for name, iana in WINDOWS_ZONES.items()}
#: Graph spells UTC in several ways in ``originalStartTimeZone``.
_UTC_ALIASES = frozenset({"utc", "etc/utc", "gmt", "etc/gmt", "z", "tzone://microsoft/utc"})
MAX_ZONE_NAME = 128


def lookup_zone(name: str) -> tzinfo | None:
    """The zone for an IANA or Windows name, or ``None`` when it is unknown."""
    candidate = (name or "").strip()
    if not candidate or len(candidate) > MAX_ZONE_NAME:
        return None
    if candidate.lower() in _UTC_ALIASES:
        return UTC
    iana = _WINDOWS_LOWER.get(candidate.lower(), candidate)
    if ".." in iana or iana.startswith("/"):
        return None
    try:
        return ZoneInfo(iana)
    except (ZoneInfoNotFoundError, ValueError, OSError):
        return None


def zone_input(value: object, field: str, *, default: str = "") -> tuple[str, tzinfo]:
    """The caller's zone name (kept for Graph) and the resolved zone."""
    if value is None or value == "":
        if not default:
            raise M365Error("invalid_payload", f"{field} is required")
        value = default
    if not isinstance(value, str):
        raise M365Error("invalid_payload", f"{field} must be a time zone name")
    name = value.strip()
    zone = lookup_zone(name)
    if zone is None:
        raise M365Error(
            "invalid_payload",
            f"{field} is not a known IANA (Europe/Berlin) or Windows (W. Europe Standard Time) zone",
        )
    return name, zone


def to_local(moment: datetime, zone: tzinfo) -> datetime:
    return moment.astimezone(zone).replace(tzinfo=None)


